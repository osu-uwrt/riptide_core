function v = talos_nav_raw_pack(raw)
%TALOS_NAV_RAW_PACK Flatten one set of samples, see talos_nav_raw_unpack. Stamps keep their bits.
%#codegen
v = [double(raw.imu.valid); typecast(raw.imu.stamp, 'double'); raw.imu.orientation; raw.imu.omega; ...
    raw.imu.accel; raw.imu.cov_o(:); raw.imu.cov_w(:); raw.imu.cov_a(:); raw.imu.frame; ...
    double(raw.fog.valid); typecast(raw.fog.stamp, 'double'); raw.fog.omega; raw.fog.cov(:); raw.fog.frame; ...
    double(raw.dvl.valid); typecast(raw.dvl.stamp, 'double'); raw.dvl.vel; raw.dvl.cov(:); raw.dvl.frame; ...
    double(raw.depth.valid); typecast(raw.depth.stamp, 'double'); raw.depth.z; raw.depth.var; raw.depth.frame; ...
    double(raw.set_pose.valid); typecast(raw.set_pose.stamp, 'double'); raw.set_pose.pos; raw.set_pose.quat; ...
    raw.set_pose.cov(:); raw.set_pose.frame];
end
