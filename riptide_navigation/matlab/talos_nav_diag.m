function a = age_ms(stamp, now)
a = -1;
if stamp ~= 0
    a = double(now - stamp) * 1e-6;
end
end

function h = heading_std(S)
pc = talos_nav_pose_covariance('ros', S.F.x, S.F.P);
h = sqrt(max(0, pc(6, 6))) * 180 / pi;
end
